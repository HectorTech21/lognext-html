let currentLang = localStorage.getItem('language') || 'es';

function setLanguage(lang) {
  if (!translations[lang]) return;
  currentLang = lang;
  localStorage.setItem('language', lang);
  updateContent();
  
  document.querySelectorAll('.language-switcher a, .language-switcher.mobile a').forEach(link => {
    if (link.textContent.toLowerCase() === lang || 
        (lang === 'es' && link.textContent === 'ES') ||
        (lang === 'en' && link.textContent === 'EN') ||
        (lang === 'fr' && link.textContent === 'FR')) {
      link.classList.add('active');
    } else {
      link.classList.remove('active');
    }
  });
}

function updateContent() {
  const t = translations[currentLang];
  if (!t) return;
  
  document.querySelectorAll('[data-i18n]').forEach(element => {
    const key = element.getAttribute('data-i18n');
    if (t[key] !== undefined) {
      element.textContent = t[key];
    }
  });
}

function initMobileMenu() {
  const menuToggle = document.querySelector('.menu-toggle');
  const mainNav = document.querySelector('.main-nav');
  if (!menuToggle || !mainNav) return;
  
  menuToggle.addEventListener('click', function() {
    menuToggle.classList.toggle('active');
    mainNav.classList.toggle('active');
    document.body.style.overflow = mainNav.classList.contains('active') ? 'hidden' : '';
  });
  
  const menuLinks = document.querySelectorAll('.menu a, .mobile-actions a');
  menuLinks.forEach(function(link) {
    link.addEventListener('click', function() {
      if (window.innerWidth <= 768) {
        menuToggle.classList.remove('active');
        mainNav.classList.remove('active');
        document.body.style.overflow = '';
      }
    });
  });
  
  const dropdowns = document.querySelectorAll('.has-dropdown');
  dropdowns.forEach(function(dropdown) {
    const link = dropdown.querySelector('a');
    if (link) {
      link.addEventListener('click', function(e) {
        if (window.innerWidth <= 768) {
          e.preventDefault();
          dropdown.classList.toggle('active');
        }
      });
    }
  });
}

function initHeroVideo() {
  const video = document.getElementById('heroVideo');
  const playPauseBtn = document.getElementById('videoPlayPauseBtn');
  
  if (!video || !playPauseBtn) return;
  
  // Si el video tiene autoplay, aseguramos que esté reproduciéndose
  if (video.hasAttribute('autoplay')) {
    video.play();
  }
  
  function toggleVideo() {
    if (video.paused) {
      video.play();
      playPauseBtn.innerHTML = `<svg width="40" height="40" viewBox="0 0 24 24" fill="none" stroke="white" stroke-width="2">
        <rect x="6" y="4" width="4" height="16" fill="white" stroke="white"/>
        <rect x="14" y="4" width="4" height="16" fill="white" stroke="white"/>
      </svg>`;
    } else {
      video.pause();
      playPauseBtn.innerHTML = `<svg width="40" height="40" viewBox="0 0 24 24" fill="none" stroke="white" stroke-width="2">
        <polygon points="5 3 19 12 5 21 5 3" fill="white" stroke="white"/>
      </svg>`;
    }
  }
  
  playPauseBtn.addEventListener('click', (e) => {
    e.stopPropagation();
    toggleVideo();
  });
  
  video.addEventListener('click', () => {
    toggleVideo();
  });
  
  video.addEventListener('ended', () => {
    video.currentTime = 0;
    playPauseBtn.innerHTML = `<svg width="40" height="40" viewBox="0 0 24 24" fill="none" stroke="white" stroke-width="2">
      <polygon points="5 3 19 12 5 21 5 3" fill="white" stroke="white"/>
    </svg>`;
  });
}

function initCounters() {
  const counters = document.querySelectorAll('.stat-number');
  if (!counters.length) return;
  
  const animateCounter = (counter) => {
    const target = parseInt(counter.getAttribute('data-target'));
    let current = 0;
    const increment = target / 50;
    const updateCounter = () => {
      current += increment;
      if (current < target) {
        counter.textContent = Math.ceil(current);
        requestAnimationFrame(updateCounter);
      } else {
        counter.textContent = target;
      }
    };
    updateCounter();
  };
  
  const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        animateCounter(entry.target);
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.5 });
  
  counters.forEach(counter => observer.observe(counter));
}

function initCarousel() {
  const track = document.getElementById('carouselTrack');
  const prevBtn = document.getElementById('prevBtn');
  const nextBtn = document.getElementById('nextBtn');
  const dotsContainer = document.getElementById('carouselDots');
  
  if (!track || !prevBtn || !nextBtn) return;
  
  const cards = document.querySelectorAll('.carousel-card');
  const cardCount = cards.length;
  let currentIndex = 0;
  let autoSlideInterval;
  
  if (dotsContainer) {
    for (let i = 0; i < cardCount; i++) {
      const dot = document.createElement('div');
      dot.classList.add('dot');
      if (i === 0) dot.classList.add('active');
      dot.addEventListener('click', () => goToSlide(i));
      dotsContainer.appendChild(dot);
    }
  }
  
  const dots = document.querySelectorAll('.dot');
  
  function updateCarousel() {
    if (cards.length === 0) return;
    const cardWidth = cards[0].offsetWidth + 25;
    track.style.transform = `translateX(-${currentIndex * cardWidth}px)`;
    if (dots.length) {
      dots.forEach((dot, i) => {
        dot.classList.toggle('active', i === currentIndex);
      });
    }
  }
  
  function goToSlide(index) {
    currentIndex = index;
    updateCarousel();
    resetAutoSlide();
  }
  
  function nextSlide() {
    currentIndex = (currentIndex + 1) % cardCount;
    updateCarousel();
  }
  
  function prevSlide() {
    currentIndex = (currentIndex - 1 + cardCount) % cardCount;
    updateCarousel();
  }
  
  function startAutoSlide() {
    if (autoSlideInterval) clearInterval(autoSlideInterval);
    autoSlideInterval = setInterval(nextSlide, 4000);
  }
  
  function resetAutoSlide() {
    clearInterval(autoSlideInterval);
    startAutoSlide();
  }
  
  function pauseAutoSlide() {
    clearInterval(autoSlideInterval);
  }
  
  prevBtn.addEventListener('click', () => {
    prevSlide();
    resetAutoSlide();
  });
  
  nextBtn.addEventListener('click', () => {
    nextSlide();
    resetAutoSlide();
  });
  
  track.addEventListener('mouseenter', pauseAutoSlide);
  track.addEventListener('mouseleave', startAutoSlide);
  
  window.addEventListener('resize', () => {
    updateCarousel();
  });
  
  startAutoSlide();
  updateCarousel();
}

function initScrollReveal() {
  const revealElements = document.querySelectorAll('.scroll-reveal');
  if (!revealElements.length) return;
  
  const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.classList.add('revealed');
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.2 });
  
  revealElements.forEach(el => observer.observe(el));
}

function initAnimatedBackground() {
  const statsSection = document.querySelector('.about-stats');
  if (!statsSection) return;
  
  for (let i = 0; i < 25; i++) {
    const particle = document.createElement('div');
    particle.classList.add('stat-particle');
    particle.style.left = Math.random() * 100 + '%';
    particle.style.top = Math.random() * 100 + '%';
    particle.style.animationDelay = Math.random() * 8 + 's';
    particle.style.animationDuration = 4 + Math.random() * 4 + 's';
    statsSection.appendChild(particle);
  }
}

// Esperar a que el DOM esté listo
document.addEventListener('DOMContentLoaded', function() {
  // Configurar idioma
  const langLinks = document.querySelectorAll('.language-switcher a, .language-switcher.mobile a');
  langLinks.forEach(function(link) {
    link.addEventListener('click', function(e) {
      e.preventDefault();
      const lang = this.textContent.toLowerCase();
      setLanguage(lang);
    });
  });
  setLanguage(currentLang);
  
  // Inicializar todos los componentes
  initMobileMenu();
  initHeroVideo();
  initCounters();
  initCarousel();
  initScrollReveal();
  initAnimatedBackground();
});